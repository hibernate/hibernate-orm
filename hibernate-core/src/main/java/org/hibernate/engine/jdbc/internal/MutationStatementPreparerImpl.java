package org.hibernate.engine.jdbc.internal;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;

import jakarta.annotation.Nonnull;
import org.hibernate.AssertionFailure;
import org.hibernate.engine.jdbc.spi.JdbcServices;
import org.hibernate.engine.jdbc.spi.MutationStatementPreparer;
import org.hibernate.engine.jdbc.spi.SqlExceptionHelper;
import org.hibernate.resource.jdbc.spi.JdbcSessionContext;
import org.hibernate.resource.jdbc.spi.LogicalConnectionImplementor;

/**
 * @author Steve Ebersole
 */
public class MutationStatementPreparerImpl implements MutationStatementPreparer {
	private final @Nonnull JdbcCoordinatorImpl jdbcCoordinator;
	private final @Nonnull JdbcServices jdbcServices;

	public MutationStatementPreparerImpl(
			@Nonnull JdbcCoordinatorImpl jdbcCoordinator,
			@Nonnull JdbcServices jdbcServices) {
		this.jdbcCoordinator = jdbcCoordinator;
		this.jdbcServices = jdbcServices;
	}

	@Override
	@Nonnull
	public PreparedStatement prepareStatement(@Nonnull String sql, boolean isCallable) {
		return buildPreparedStatementPreparationTemplate( sql, isCallable ).prepareStatement();
	}

	@Nonnull
	private StatementPreparationTemplate buildPreparedStatementPreparationTemplate(
			@Nonnull String sql,
			final boolean isCallable) {
		return new StatementPreparationTemplate( sql ) {
			@Override
			@Nonnull
			protected PreparedStatement doPrepare() throws SQLException {
				//noinspection resource
				return isCallable
						? connection().prepareCall( sql )
						: connection().prepareStatement( sql );
			}
		};
	}

	@Override
	@Nonnull
	public PreparedStatement prepareStatement(@Nonnull String sql, int autoGeneratedKeys) {
		if ( autoGeneratedKeys == PreparedStatement.RETURN_GENERATED_KEYS ) {
			checkAutoGeneratedKeysSupportEnabled();
		}
		return new StatementPreparationTemplate( sql ) {
			@Nonnull
			public PreparedStatement doPrepare() throws SQLException {
				//noinspection resource
				return connection().prepareStatement( sql, autoGeneratedKeys );
			}
		}.prepareStatement();
	}

	private void checkAutoGeneratedKeysSupportEnabled() {
		if ( ! settings().isGetGeneratedKeysEnabled() ) {
			throw new AssertionFailure( "getGeneratedKeys() support is not enabled" );
		}
	}

	@Override
	@Nonnull
	public PreparedStatement prepareStatement(@Nonnull String sql, @Nonnull String[] columnNames) {
		checkAutoGeneratedKeysSupportEnabled();
		return new StatementPreparationTemplate( sql ) {
			@Nonnull
			public PreparedStatement doPrepare() throws SQLException {
				//noinspection resource
				return connection().prepareStatement( sql, columnNames );
			}
		}.prepareStatement();
	}

	private abstract class StatementPreparationTemplate {
		protected final @Nonnull String sql;

		protected StatementPreparationTemplate(@Nonnull String incomingSql) {
			final String inspectedSql =
					jdbcCoordinator.getJdbcSessionOwner().getJdbcSessionContext()
							.getStatementInspector().inspect( incomingSql );
			sql = inspectedSql == null ? incomingSql : inspectedSql;
		}

		@Nonnull
		public PreparedStatement prepareStatement() {
			try {
				final var jdbcSessionOwner = jdbcCoordinator.getJdbcSessionOwner();
				final var jdbcEventHandler = jdbcSessionOwner.getJdbcSessionContext().getEventHandler();
				final var eventMonitor = jdbcSessionOwner.getEventMonitor();
				final var jdbcPreparedStatementCreation = eventMonitor.beginJdbcPreparedStatementCreationEvent();
				final PreparedStatement preparedStatement;
				try {
					jdbcEventHandler.jdbcPrepareStatementStart();
					preparedStatement = doPrepare();
					setStatementTimeout( preparedStatement );
				}
				finally {
					eventMonitor.completeJdbcPreparedStatementCreationEvent( jdbcPreparedStatementCreation, sql );
					jdbcEventHandler.jdbcPrepareStatementEnd();
				}
				postProcess( preparedStatement );
				return preparedStatement;
			}
			catch (SQLException e) {
				throw sqlExceptionHelper().convert( e, "Could not prepare statement", sql );
			}
		}

		@Nonnull
		protected abstract PreparedStatement doPrepare() throws SQLException;

		public void postProcess(@Nonnull PreparedStatement preparedStatement) throws SQLException {
			jdbcCoordinator.getLogicalConnection().getResourceRegistry().register( preparedStatement, true );
//			logicalConnection().notifyObserversStatementPrepared();
		}

		private void setStatementTimeout(@Nonnull PreparedStatement preparedStatement) throws SQLException {
			final int remainingTransactionTimeOutPeriod = jdbcCoordinator.determineRemainingTransactionTimeOutPeriod();
			if ( remainingTransactionTimeOutPeriod > 0 ) {
				preparedStatement.setQueryTimeout( remainingTransactionTimeOutPeriod );
			}
		}
	}

	@Nonnull
	protected final Connection connection() {
		return logicalConnection().getPhysicalConnection();
	}

	@Nonnull
	protected final LogicalConnectionImplementor logicalConnection() {
		return jdbcCoordinator.getLogicalConnection();
	}

	@Nonnull
	protected final SqlExceptionHelper sqlExceptionHelper() {
		return jdbcServices.getSqlExceptionHelper();
	}

	@Nonnull
	protected final JdbcSessionContext settings() {
		return jdbcCoordinator.getJdbcSessionOwner().getJdbcSessionContext();
	}
}
