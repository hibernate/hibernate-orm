package org.hibernate.engine.jdbc.spi;

import java.sql.CallableStatement;
import java.sql.PreparedStatement;
import java.sql.Statement;

import org.hibernate.ScrollMode;

import jakarta.annotation.Nonnull;
import jakarta.annotation.Nullable;

/**
 * Interface to the object that prepares JDBC {@link Statement}s and {@link PreparedStatement}s
 * on behalf of a {@link JdbcCoordinator}.
 *
 * @author Steve Ebersole
 * @author Brett Meyer
 *
 * @see JdbcCoordinator#getStatementPreparer()
 */
public interface StatementPreparer {
	/**
	 * Create a statement.
	 *
	 * @return the statement
	 */
	@Nonnull
	Statement createStatement();

	/**
	 * Prepare a statement.
	 *
	 * @param sql The SQL the statement to be prepared
	 *
	 * @return the prepared statement
	 */
	@Nonnull
	PreparedStatement prepareStatement(@Nonnull String sql);

	/**
	 * Prepare a statement.
	 *
	 * @param sql The SQL the statement to be prepared
	 *
	 * @return the prepared statement
	 *
	 * @since 7.0
	 */
	@Nonnull
	CallableStatement prepareCallableStatement(@Nonnull String sql);

	/**
	 * Prepare a statement.
	 *
	 * @param sql The SQL the statement to be prepared
	 * @param isCallable Whether to prepare as a callable statement.
	 *
	 * @return the prepared statement
	 */
	@Nonnull
	PreparedStatement prepareStatement(@Nonnull String sql, boolean isCallable);

	/**
	 * Prepare an INSERT statement, specifying how auto-generated (by the database) keys should be handled.
	 * Really this is a boolean, but JDBC opted to define it instead using int constants:
	 * <ul>
	 *     <li>{@link PreparedStatement#RETURN_GENERATED_KEYS}</li>
	 *     <li>{@link PreparedStatement#NO_GENERATED_KEYS}</li>
	 * </ul>
	 * <p>
	 * Generated keys are accessed afterward via {@link PreparedStatement#getGeneratedKeys}.
	 *
	 * @param sql The INSERT SQL
	 * @param autoGeneratedKeys The autoGeneratedKeys flag
	 *
	 * @return the prepared statement
	 *
	 * @see java.sql.Connection#prepareStatement(String, int)
	 */
	@Nonnull
	PreparedStatement prepareStatement(@Nonnull String sql, int autoGeneratedKeys);

	/**
	 * Prepare an INSERT statement, specifying columns which are auto-generated values to be returned.
	 * Generated keys are accessed afterward via {@link PreparedStatement#getGeneratedKeys}.
	 *
	 * @param sql - the SQL for the statement to be prepared
	 * @param columnNames The name of the columns to be returned in the generated keys result set.
	 *
	 * @return the prepared statement
	 *
	 * @see java.sql.Connection#prepareStatement(String, String[])
	 */
	@Nonnull
	PreparedStatement prepareStatement(@Nonnull String sql, @Nonnull String[] columnNames);

	/**
	 * Get a prepared statement for use in loading / querying, leaving any pending JDBC batch queued.
	 *
	 * @param sql The SQL the statement to be prepared
	 *
	 * @return the prepared statement
	 */
	@Nonnull
	PreparedStatement prepareQueryStatement(@Nonnull String sql);

	/**
	 * Get a prepared statement for use in loading / querying, leaving any pending JDBC batch queued.
	 *
	 * @param sql The SQL the statement to be prepared
	 * @param isCallable Whether to prepare as a callable statement.
	 *
	 * @return the prepared statement
	 */
	@Nonnull
	PreparedStatement prepareQueryStatement(@Nonnull String sql, boolean isCallable);

	/**
	 * Get a prepared statement for use in loading / querying, leaving any pending JDBC batch queued.
	 *
	 * @param sql The SQL the statement to be prepared
	 * @param isCallable Whether to prepare as a callable statement.
	 * @param scrollMode (optional) scroll mode to be applied to the resulting result set;
	 *                   may be null to indicate no scrolling should be applied.
	 *
	 * @return the prepared statement
	 */
	@Nonnull
	PreparedStatement prepareQueryStatement(@Nonnull String sql, boolean isCallable, @Nullable ScrollMode scrollMode);
}
