package org.hibernate.persister.entity.mutation;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.function.Consumer;
import java.util.function.Function;

import jakarta.annotation.Nonnull;
import jakarta.annotation.Nullable;

import org.hibernate.Internal;
import org.hibernate.engine.jdbc.batch.spi.BatchKey;
import org.hibernate.engine.jdbc.mutation.JdbcValueBindings;
import org.hibernate.engine.jdbc.mutation.OperationResultChecker;
import org.hibernate.engine.jdbc.mutation.ParameterUsage;
import org.hibernate.engine.jdbc.mutation.internal.NoBatchKeyAccess;
import org.hibernate.engine.jdbc.mutation.spi.BatchKeyAccess;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.engine.spi.SharedSessionContractImplementor;
import org.hibernate.jdbc.Expectation;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.sql.ast.spi.model.ColumnValueBinding;
import org.hibernate.sql.ast.spi.model.ColumnValueParameter;
import org.hibernate.sql.ast.spi.model.ColumnWriteFragment;
import org.hibernate.sql.ast.spi.model.MutatingTableReference;
import org.hibernate.sql.ast.spi.model.TableInsertSelect;
import org.hibernate.sql.ast.spi.query.expression.ColumnReference;
import org.hibernate.sql.ast.spi.model.TableMutation;
import org.hibernate.sql.model.MutationOperationGroup;
import org.hibernate.sql.model.internal.MutationGroupSingle;
import org.hibernate.sql.model.internal.MutationGroupStandard;
import org.hibernate.sql.spi.mutation.MutationType;

/// Base support for writing the rows of a table derived from the tables which
/// hold the current data of an entity, such as a history table or an audit log
/// table.
///
/// A row of such an auxiliary table is never assembled from the state of an
/// entity instance. It is copied from the current row, so that it holds exactly
/// what the database stored there, including values generated by the database,
/// and columns which the last statement did not write.
///
/// This class knows how to build and execute the statement which copies a row.
/// A subclass decides which rows are copied, what else the auxiliary table
/// records about each row, and how its existing rows are maintained.
///
/// @author Gavin King
/// @since 8.0
@Internal
public abstract class AbstractAuxiliaryRowWriter extends AbstractMutationCoordinator {
	private static final OperationResultChecker ANY_ROW_COUNT = (statementDetails, affectedRowCount, batchPosition) -> true;

	protected AbstractAuxiliaryRowWriter(@Nonnull EntityPersister entityPersister, @Nonnull SessionFactoryImplementor factory) {
		super( entityPersister, factory );
	}

	@Nonnull
	public EntityPersister getEntityPersister() {
		return entityPersister();
	}

	@Nullable
	@Override
	protected BatchKey getBatchKey() {
		return null;
	}

	/// A mapping of the auxiliary table which has the key of the given table of
	/// the entity. No operation on it expects a particular row count, since the
	/// row it reads or writes may legitimately be absent.
	protected static EntityTableMapping createAuxiliaryTableMapping(
			@Nonnull EntityTableMapping currentTable, @Nonnull String auxiliaryTableName) {
		return new EntityTableMappingImpl(
				auxiliaryTableName,
				currentTable.relativePosition(),
				currentTable.getKeyMapping(),
				false,
				false,
				currentTable.isIdentifierTable(),
				false,
				currentTable.getAttributeIndexes(),
				Expectation.None.INSTANCE,
				null,
				false,
				Expectation.None.INSTANCE,
				null,
				false,
				false,
				Expectation.None.INSTANCE,
				null,
				false,
				false,
				false
		);
	}

	/// Creates the insert which copies the row of the given table of the entity
	/// to its auxiliary table.
	///
	/// A table other than the identifier table may have no row for an entity.
	/// Its copy is anchored to the identifier table, so that the auxiliary table
	/// receives a row with null columns in that case.
	///
	/// @param copiedColumns the columns which the auxiliary table copies
	/// @param assignments creates the bindings of the columns of the auxiliary
	///                    table which do not come from the current row
	protected TableInsertSelect createCopy(
			@Nonnull EntityTableMapping auxiliaryTable,
			@Nonnull EntityTableMapping currentTable,
			@Nonnull List<String> copiedColumns,
			@Nonnull Function<MutatingTableReference, List<ColumnValueBinding>> assignments) {
		final var target = new MutatingTableReference( auxiliaryTable );
		final Set<String> keyColumns = new HashSet<>();
		final List<ColumnValueBinding> keyRestrictions = new ArrayList<>();
		currentTable.getKeyMapping().forEachKeyColumn( (position, key) -> {
			final var column = new ColumnReference( target, key );
			keyColumns.add( key.getColumnName() );
			keyRestrictions.add( new ColumnValueBinding( column,
					new ColumnWriteFragment( "?", new ColumnValueParameter( column, ParameterUsage.RESTRICT ), key ) ) );
		} );
		final List<String> nonKeyColumns = new ArrayList<>( copiedColumns.size() );
		for ( String column : copiedColumns ) {
			if ( !keyColumns.contains( column ) ) {
				nonKeyColumns.add( column );
			}
		}
		if ( currentTable.isIdentifierTable() ) {
			return new TableInsertSelect( target, entityPersister(), currentTable.getTableName(),
					nonKeyColumns, assignments.apply( target ), keyRestrictions );
		}
		else {
			final var identifierTable = entityPersister().getIdentifierTableMapping();
			final List<String> anchorKeyColumns = new ArrayList<>( keyRestrictions.size() );
			identifierTable.getKeyMapping().forEachKeyColumn( (position, key) -> anchorKeyColumns.add( key.getColumnName() ) );
			return new TableInsertSelect( target, entityPersister(), currentTable.getTableName(),
					nonKeyColumns, assignments.apply( target ), keyRestrictions,
					identifierTable.getTableName(), anchorKeyColumns );
		}
	}

	/// Creates the group of operations which execute the given mutations of auxiliary tables.
	protected MutationOperationGroup createOperationGroup(
			@Nonnull MutationType type, @Nonnull List<? extends TableMutation<?>> mutations) {
		return createOperationGroup( null, mutations.size() == 1
				? new MutationGroupSingle( type, entityPersister(), mutations.get( 0 ) )
				: new MutationGroupStandard( type, entityPersister(), mutations ) );
	}

	/// Binds the key of a row of the given auxiliary table.
	protected void bindKey(
			@Nonnull Object id,
			@Nonnull JdbcValueBindings bindings,
			@Nonnull EntityTableMapping auxiliaryTable,
			@Nonnull SharedSessionContractImplementor session) {
		breakDownKeyJdbcValues( id, null, session, bindings, auxiliaryTable );
	}

	/// Executes operations which accept any row count.
	///
	/// @param batchKey the key of the batch to which the statements are added
	///                 within a transaction, or `null` to execute them at once
	protected void execute(
			@Nonnull MutationOperationGroup group,
			@Nullable BatchKey batchKey,
			@Nonnull SharedSessionContractImplementor session,
			@Nonnull Consumer<JdbcValueBindings> binder) {
		execute( group, batchKey, session, binder, ANY_ROW_COUNT );
	}

	/// Executes operations, checking the row count of each statement which is
	/// not added to a batch.
	protected void execute(
			@Nonnull MutationOperationGroup group,
			@Nullable BatchKey batchKey,
			@Nonnull SharedSessionContractImplementor session,
			@Nonnull Consumer<JdbcValueBindings> binder,
			@Nonnull OperationResultChecker resultChecker) {
		final var executor = mutationExecutorService.createExecutor( batchKeyAccess( batchKey, session ), group, session );
		try {
			binder.accept( executor.getJdbcValueBindings() );
			executor.execute( null, null, null, resultChecker, session );
		}
		finally {
			executor.release();
		}
	}

	private static BatchKeyAccess batchKeyAccess(@Nullable BatchKey batchKey, SharedSessionContractImplementor session) {
		return batchKey != null && session.getTransactionCoordinator().isTransactionActive()
				? () -> batchKey
				: NoBatchKeyAccess.INSTANCE;
	}
}
