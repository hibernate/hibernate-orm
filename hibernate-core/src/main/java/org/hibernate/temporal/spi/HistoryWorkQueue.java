package org.hibernate.temporal.spi;

import java.util.BitSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import jakarta.annotation.Nullable;

import org.hibernate.Incubating;
import org.hibernate.engine.spi.EntityKey;
import org.hibernate.engine.spi.SharedSessionContractImplementor;
import org.hibernate.engine.spi.TransactionCompletionCallbacks;
import org.hibernate.metamodel.mapping.SelectableMapping;
import org.hibernate.persister.entity.mutation.HistoryRevisionWriter;
import org.hibernate.persister.entity.mutation.PartitionKeyValue;

/// Transaction-scoped queue of the entities whose revisions must be written
/// to a [history table][org.hibernate.temporal.TemporalTableStrategy#HISTORY_TABLE].
///
/// An insert, update, or delete of an entity writes only the table holding
/// current data, and records the affected entity here. Before the transaction
/// completes, each recorded entity is reconciled with its history table: the
/// open revision is ended, and a new revision is copied from the current row.
/// By then the row has its final state for the changeset, including every
/// value generated by the database.
///
/// Successive changes to one entity are merged, so that a changeset produces
/// at most one revision of it:
///
/// - an entity created and removed in one changeset has no revision,
/// - an entity removed and created again has its revision replaced, and
/// - a change which does not warrant a new revision is applied to the open
///   revision, unless some other change in the changeset does warrant one.
///
/// Outside of a transaction there is no changeset to wait for, and the entity
/// is reconciled as soon as its current row has been written.
///
/// @author Gavin King
/// @since 8.0
@Incubating(since = "8.0")
public class HistoryWorkQueue implements TransactionCompletionCallbacks.BeforeCompletionCallback {
	private final Map<EntityKey, Change> changes = new LinkedHashMap<>();
	private boolean registered;

	/// Record the insertion of the current row of an entity.
	public void entityInserted(Object id, HistoryRevisionWriter writer, SharedSessionContractImplementor session) {
		add( id, Change.inserted( writer ), session );
	}

	/// Record an update of the current row of an entity.
	///
	/// @param newRevision whether the update warrants a new revision
	/// @param dirtyAttributes the modified attributes, if known
	/// @param partitionKeys the partition key of the row before the update, as far as it is known
	public void entityUpdated(
			Object id,
			boolean newRevision, @Nullable int[] dirtyAttributes,
			List<PartitionKeyValue> partitionKeys,
			HistoryRevisionWriter writer, SharedSessionContractImplementor session) {
		add( id, Change.updated( writer, newRevision, dirtyAttributes, partitionKeys ), session );
	}

	/// Record that an association wrote columns of the current row of an entity,
	/// without the entity itself being updated.
	///
	/// @param newRevision whether the write warrants a new revision; if not, the
	///                    columns are copied to the open revision
	/// @param columns the columns which were written
	/// @param partitionKeys the partition key of the row before it was written, as far as it is known
	public void entityRowWritten(
			Object id,
			boolean newRevision, List<SelectableMapping> columns,
			List<PartitionKeyValue> partitionKeys,
			HistoryRevisionWriter writer, SharedSessionContractImplementor session) {
		add( id, Change.rowWritten( writer, newRevision, columns, partitionKeys ), session );
	}

	/// Record the deletion of the current row of an entity.
	///
	/// @param partitionKeys the partition key of the deleted row, as far as it is known
	public void entityDeleted(
			Object id, List<PartitionKeyValue> partitionKeys,
			HistoryRevisionWriter writer, SharedSessionContractImplementor session) {
		add( id, Change.deleted( writer, partitionKeys ), session );
	}

	/// Called when the statements which write current rows have been executed.
	/// Outside of a transaction, the recorded entities are reconciled at once.
	public void currentRowsWritten(SharedSessionContractImplementor session) {
		if ( !registered && !changes.isEmpty() ) {
			writeRevisions( session );
		}
	}

	private void add(Object id, Change change, SharedSessionContractImplementor session) {
		if ( !registered && session.isTransactionInProgress() ) {
			final var callbacks = session.getTransactionCompletionCallbacks();
			callbacks.registerCallback( this );
			// Rollback never invokes the before-completion callback.
			callbacks.registerCallback( (success, completingSession) -> clear() );
			registered = true;
		}
		changes.merge( session.generateEntityKey( id, change.writer.getEntityPersister() ), change, Change::followedBy );
	}

	@Override
	public void doBeforeTransactionCompletion(SharedSessionContractImplementor session) {
		writeRevisions( session );
	}

	private void writeRevisions(SharedSessionContractImplementor session) {
		try {
			// End every superseded revision before opening any new one,
			// since a new revision is itself an open revision of its entity.
			for ( var entry : changes.entrySet() ) {
				final var change = entry.getValue();
				if ( change.endsRevision() ) {
					change.initialWriter.endRevision( entry.getKey().getIdentifier(), change.partitionKeys, session );
				}
			}
			for ( var entry : changes.entrySet() ) {
				final var change = entry.getValue();
				final Object id = entry.getKey().getIdentifier();
				if ( change.opensRevision() ) {
					change.writer.copyRevision( id, session );
				}
				else if ( change.refreshesRevision() ) {
					change.writer.refreshRevision( id, change.refreshedAttributes,
							change.refreshedColumns.values(), change.partitionKeys, session );
				}
			}
			session.getJdbcCoordinator().executeBatch();
		}
		finally {
			clear();
		}
	}

	private void clear() {
		changes.clear();
		registered = false;
	}

	/// The net effect of the changes made to one entity during the changeset.
	///
	/// @param initialWriter the writer for the history table holding the revision
	///                      which was open when the changeset began
	/// @param writer the writer for the history table of the current row
	/// @param hadRevision whether a revision was open when the changeset began
	/// @param exists whether the current row exists
	/// @param newRevision whether some change warrants a new revision
	/// @param refreshedAttributes the attributes modified by changes which do
	///                            not warrant a new revision
	/// @param refreshedColumns columns of no attribute, written by changes which
	///                         do not warrant a new revision, by name
	/// @param partitionKeys the partition key of the revision which was open
	///                      when the changeset began, as far as it is known
	private record Change(
			HistoryRevisionWriter initialWriter,
			HistoryRevisionWriter writer,
			boolean hadRevision,
			boolean exists,
			boolean newRevision,
			BitSet refreshedAttributes,
			Map<String, SelectableMapping> refreshedColumns,
			List<PartitionKeyValue> partitionKeys) {
		private static final BitSet NONE = new BitSet( 0 );

		static Change inserted(HistoryRevisionWriter writer) {
			return new Change( writer, writer, false, true, true, NONE, Map.of(), List.of() );
		}

		static Change updated(
				HistoryRevisionWriter writer, boolean newRevision, @Nullable int[] dirtyAttributes,
				List<PartitionKeyValue> partitionKeys) {
			final BitSet attributes;
			if ( newRevision || dirtyAttributes == null || dirtyAttributes.length == 0 ) {
				attributes = NONE;
			}
			else {
				attributes = new BitSet();
				for ( int index : dirtyAttributes ) {
					attributes.set( index );
				}
			}
			return new Change( writer, writer, true, true, newRevision, attributes, Map.of(), partitionKeys );
		}

		static Change rowWritten(
				HistoryRevisionWriter writer, boolean newRevision, List<SelectableMapping> columns,
				List<PartitionKeyValue> partitionKeys) {
			if ( newRevision ) {
				return updated( writer, true, null, partitionKeys );
			}
			final Map<String, SelectableMapping> written = new LinkedHashMap<>();
			for ( var column : columns ) {
				written.put( column.getSelectionExpression(), column );
			}
			return new Change( writer, writer, true, true, false, NONE, written, partitionKeys );
		}

		static Change deleted(HistoryRevisionWriter writer, List<PartitionKeyValue> partitionKeys) {
			return new Change( writer, writer, true, false, false, NONE, Map.of(), partitionKeys );
		}

		Change followedBy(Change next) {
			final BitSet attributes;
			if ( next.refreshedAttributes.isEmpty() ) {
				attributes = refreshedAttributes;
			}
			else if ( refreshedAttributes.isEmpty() ) {
				attributes = next.refreshedAttributes;
			}
			else {
				attributes = (BitSet) refreshedAttributes.clone();
				attributes.or( next.refreshedAttributes );
			}
			final Map<String, SelectableMapping> columns;
			if ( next.refreshedColumns.isEmpty() ) {
				columns = refreshedColumns;
			}
			else if ( refreshedColumns.isEmpty() ) {
				columns = next.refreshedColumns;
			}
			else {
				columns = new LinkedHashMap<>( refreshedColumns );
				columns.putAll( next.refreshedColumns );
			}
			return new Change(
					initialWriter,
					next.writer,
					hadRevision,
					next.exists,
					// a row which was removed and created again is a new revision
					newRevision || next.newRevision || !exists && next.exists,
					attributes,
					columns,
					partitionKeys
			);
		}

		boolean endsRevision() {
			return hadRevision && ( !exists || newRevision );
		}

		boolean opensRevision() {
			return exists && ( !hadRevision || newRevision );
		}

		boolean refreshesRevision() {
			return exists && hadRevision && !newRevision
				&& ( !refreshedAttributes.isEmpty() || !refreshedColumns.isEmpty() );
		}
	}
}
