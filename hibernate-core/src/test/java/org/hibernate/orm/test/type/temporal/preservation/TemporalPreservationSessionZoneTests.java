package org.hibernate.orm.test.type.temporal.preservation;

import java.time.Duration;
import java.time.Instant;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.function.Consumer;

import jakarta.persistence.Entity;
import jakarta.persistence.Id;

import org.hibernate.Session;
import org.hibernate.annotations.CurrentTimestamp;
import org.hibernate.annotations.SourceType;
import org.hibernate.annotations.TemporalPreservationPolicy;
import org.hibernate.annotations.TimeZoneRepresentation;
import org.hibernate.boot.MetadataSources;
import org.hibernate.cfg.MappingSettings;
import org.hibernate.dialect.H2Dialect;
import org.hibernate.dialect.HSQLDialect;
import org.hibernate.dialect.MySQLDialect;
import org.hibernate.dialect.OracleDialect;
import org.hibernate.dialect.PostgreSQLDialect;
import org.hibernate.dialect.SQLServerDialect;
import org.hibernate.engine.spi.SessionFactoryImplementor;

import org.hibernate.testing.orm.junit.DialectContext;
import org.hibernate.testing.orm.junit.RequiresDialect;
import org.hibernate.testing.util.ServiceRegistryUtil;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/// Verifies against a live database that, with temporal preservation
/// enabled, what the database itself computes for an instant does not depend
/// on the time zone of its session: a timestamp it generates, and a
/// comparison between two of its columns.
///
/// @author Steve Ebersole
@RequiresDialect(H2Dialect.class)
@RequiresDialect(HSQLDialect.class)
@RequiresDialect(value = PostgreSQLDialect.class, matchSubTypes = false)
@RequiresDialect(MySQLDialect.class)
@RequiresDialect(SQLServerDialect.class)
@RequiresDialect(OracleDialect.class)
class TemporalPreservationSessionZoneTests {
	private static final String[] DATABASE_SESSION_ZONES = { null, "Asia/Kathmandu", "America/New_York" };

	/// A timestamp generated by the database is the current instant, also
	/// where the column holds the date and time at UTC and the current
	/// timestamp of the database is in the time zone of its session.
	@Test
	void generatedTimestampIsTheCurrentInstant() {
		inEverySessionZone( session -> {
			final var entity = new WithGenerated();
			entity.id = 1;
			session.persist( entity );
			session.flush();
			session.clear();
			final var read = session.find( WithGenerated.class, 1 );
			assertThat( Duration.between( Instant.now(), read.recordedAt ).abs() ).isLessThan( Duration.ofMinutes( 5 ) );
			assertThat( Duration.between( Instant.now(), read.normalizedAt.toInstant() ).abs() )
					.isLessThan( Duration.ofMinutes( 5 ) );
		} );
	}

	/// Two columns which hold the same instant compare as equal. Where one
	/// holds the date and time at UTC and the other denotes an instant by
	/// itself, the database would compare them in the time zone of its
	/// session, so the comparison is rejected.
	@Test
	void columnsAreComparedByTheirInstantOrNotAtAll() {
		// only HSQLDB has columns of both kinds
		final boolean rejected = DialectContext.getDialect() instanceof HSQLDialect;
		inEverySessionZone( session -> {
			final var entity = new Compared();
			entity.id = 1;
			entity.inTwoColumns = OffsetDateTime.of( 2021, 3, 14, 11, 0, 0, 0, ZoneOffset.ofHours( 2 ) );
			entity.normalized = entity.inTwoColumns;
			entity.instant = entity.inTwoColumns.toInstant();
			session.persist( entity );
			session.flush();
			for ( String predicate : new String[] {
					"e.inTwoColumns = e.normalized",
					"e.inTwoColumns between e.normalized and e.normalized",
					"e.instant = e.normalized",
					"e.instant in (e.normalized)",
					// tuples are compared element by element
					"(e.id, e.instant) = (e.id, e.normalized)",
					"(e.id, e.instant) in ((e.id, e.normalized))"
			} ) {
				final String query = "select count(e) from Compared e where " + predicate;
				if ( rejected ) {
					assertThatThrownBy( () -> session.createQuery( query, Long.class ).getSingleResult() )
							.as( predicate )
							.hasStackTraceContaining( "in the time zone of its session" );
				}
				else {
					assertThat( session.createQuery( query, Long.class ).getSingleResult() ).as( predicate ).isEqualTo( 1L );
				}
			}
			// both hold the date and time at UTC, or both denote an instant
			assertThat( session.createQuery( "select count(e) from Compared e where e.inTwoColumns = e.instant", Long.class )
					.getSingleResult() ).isEqualTo( 1L );
		} );
	}

	private static void inEverySessionZone(Consumer<Session> action) {
		final var builder = ServiceRegistryUtil.serviceRegistryBuilder();
		builder.applySetting( "hibernate.hbm2ddl.auto", "create-drop" );
		builder.applySetting( MappingSettings.TEMPORAL_PRESERVATION, true );
		try ( var registry = builder.build();
				var factory = (SessionFactoryImplementor) new MetadataSources( registry )
						.addAnnotatedClass( WithGenerated.class )
						.addAnnotatedClass( Compared.class )
						.buildMetadata()
						.buildSessionFactory() ) {
			for ( String zone : DATABASE_SESSION_ZONES ) {
				TemporalPreservationOffsetTests.inSession( factory, null, zone, action );
			}
		}
	}

	@Entity(name = "WithGenerated")
	static class WithGenerated {
		@Id
		Integer id;
		@CurrentTimestamp(source = SourceType.DB)
		Instant recordedAt;
		@CurrentTimestamp(source = SourceType.DB)
		@TimeZoneRepresentation(TimeZoneRepresentation.Type.INLINE)
		@TemporalPreservationPolicy(TemporalPreservationPolicy.Type.NORMALIZED)
		OffsetDateTime normalizedAt;
	}

	@Entity(name = "Compared")
	static class Compared {
		@Id
		Integer id;
		@TimeZoneRepresentation(TimeZoneRepresentation.Type.COLUMN)
		OffsetDateTime inTwoColumns;
		@TimeZoneRepresentation(TimeZoneRepresentation.Type.INLINE)
		@TemporalPreservationPolicy(TemporalPreservationPolicy.Type.NORMALIZED)
		OffsetDateTime normalized;
		Instant instant;
	}
}
