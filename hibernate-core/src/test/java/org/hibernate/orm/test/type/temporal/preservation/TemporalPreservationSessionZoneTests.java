/// Verifies against a live database that, with temporal preservation
/// enabled, what the database itself computes for an instant does not depend
/// on the time zone of its session: a timestamp it generates, also for a
/// temporal table or a soft delete, a comparison between two of its
/// columns, and a comparison with its current date and time.
///
/// @author Steve Ebersole
@RequiresDialect(H2Dialect.class)
@RequiresDialect(HSQLDialect.class)
@RequiresDialect(value = PostgreSQLDialect.class, matchSubTypes = false)
@RequiresDialect(MySQLDialect.class)
@RequiresDialect(SQLServerDialect.class)
@RequiresDialect(OracleDialect.class)
class TemporalPreservationSessionZoneTests {
	private static final String[] DATABASE_SESSION_ZONES = { null, "Asia/Kathmandu", "America/New_York" };

	/// A timestamp generated by the database is the current instant, also
	/// where the column holds the date and time at UTC and the current
	/// timestamp of the database is in the time zone of its session.
	@Test
	void generatedTimestampIsTheCurrentInstant() {
		inEverySessionZone( session -> {
			final var entity = new WithGenerated();
			entity.id = 1;
			session.persist( entity );
			session.flush();
			session.clear();
			final var read = session.find( WithGenerated.class, 1 );
			assertThat( Duration.between( Instant.now(), read.recordedAt ).abs() ).isLessThan( Duration.ofMinutes( 5 ) );
			assertThat( Duration.between( Instant.now(), read.normalizedAt.toInstant() ).abs() )
					.isLessThan( Duration.ofMinutes( 5 ) );
		} );
	}

	/// A version which the database generates is the current instant. It
	/// is retrieved by a query of its own, before the row is written, and
	/// is read as the type of its column is, and not as a
	/// `java.sql.Timestamp`. The row is then found by that version.
	@Test
	void generatedVersionIsTheCurrentInstant() {
		final var builder = ServiceRegistryUtil.serviceRegistryBuilder();
		builder.applySetting( "hibernate.hbm2ddl.auto", "create-drop" );
		builder.applySetting( MappingSettings.TEMPORAL_PRESERVATION, true );
		try ( var registry = builder.build();
				var factory = (SessionFactoryImplementor) new MetadataSources( registry )
						.addAnnotatedClass( WithGeneratedVersion.class )
						.addAnnotatedClass( WithGeneratedOffsetVersion.class )
						.buildMetadata()
						.buildSessionFactory() ) {
			for ( String zone : DATABASE_SESSION_ZONES ) {
				TemporalPreservationOffsetTests.inSession( factory, null, zone, session -> {
					final var entity = new WithGeneratedVersion();
					entity.id = 1;
					final var offset = new WithGeneratedOffsetVersion();
					offset.id = 1;
					session.persist( entity );
					session.persist( offset );
					session.flush();
					assertThat( Duration.between( Instant.now(), entity.version ).abs() ).isLessThan( Duration.ofMinutes( 5 ) );
					assertThat( Duration.between( Instant.now(), offset.version.toInstant() ).abs() )
							.isLessThan( Duration.ofMinutes( 5 ) );
					final Instant first = entity.version;
					session.clear();

					// what is stored is what was generated
					final var read = session.find( WithGeneratedVersion.class, 1 );
					assertThat( read.version ).isEqualTo( first );
					final var readOffset = session.find( WithGeneratedOffsetVersion.class, 1 );
					assertThat( readOffset.version.toInstant() ).isEqualTo( offset.version.toInstant() );

					// the row is updated where its version is the one which was read
					read.name = "changed";
					readOffset.name = "changed";
					session.flush();
					assertThat( read.version ).isAfterOrEqualTo( first );
					assertThat( Duration.between( Instant.now(), read.version ).abs() ).isLessThan( Duration.ofMinutes( 5 ) );
					session.clear();
					assertThat( session.find( WithGeneratedVersion.class, 1 ).name ).isEqualTo( "changed" );
					assertThat( session.find( WithGeneratedOffsetVersion.class, 1 ).name ).isEqualTo( "changed" );
				} );
			}
		}
	}

	/// The current instant which a query asks the database for is the
	/// current instant, as an `Instant` and as an `OffsetDateTime`.
	@Test
	void currentInstantOfAQueryIsTheCurrentInstant() {
		inEverySessionZone( session -> {
			final var entity = new Compared();
			entity.id = 1;
			session.persist( entity );
			session.flush();
			final Instant instant = session.createQuery( "select instant from Compared", Instant.class )
					.getSingleResult();
			assertThat( Duration.between( Instant.now(), instant ).abs() ).isLessThan( Duration.ofMinutes( 5 ) );
			final OffsetDateTime dateTime = session.createQuery( "select offset datetime from Compared", OffsetDateTime.class )
					.getSingleResult();
			assertThat( Duration.between( Instant.now(), dateTime.toInstant() ).abs() ).isLessThan( Duration.ofMinutes( 5 ) );
		} );
	}

	/// The row start of a temporal table and the timestamp of a soft delete
	/// are the current instant, whether the timestamps of transactions come
	/// from the JVM or from the database.
	@Test
	void timestampsOfTemporalTablesAndSoftDeletesAreTheCurrentInstant() {
		for ( boolean fromDatabase : new boolean[] { false, true } ) {
			final var builder = ServiceRegistryUtil.serviceRegistryBuilder();
			builder.applySetting( "hibernate.hbm2ddl.auto", "create-drop" );
			builder.applySetting( MappingSettings.TEMPORAL_PRESERVATION, true );
			builder.applySetting( StateManagementSettings.TEMPORAL_TABLE_STRATEGY, "SINGLE_TABLE" );
			builder.applySetting( StateManagementSettings.USE_SERVER_TRANSACTION_TIMESTAMPS, fromDatabase );
			// Oracle allows no column with a time zone in a primary key, so the
			// row start of a temporal table cannot be stored as an Instant is
			final boolean temporalTables = !( DialectContext.getDialect() instanceof OracleDialect );
			try ( var registry = builder.build();
					var factory = (SessionFactoryImplementor) new MetadataSources( registry )
							.addAnnotatedClasses( temporalTables
									? new Class<?>[] { SoftDeleted.class, WithHistory.class }
									: new Class<?>[] { SoftDeleted.class } )
							.buildMetadata()
							.buildSessionFactory() ) {
				final int[] ids = { 0 };
				for ( String zone : DATABASE_SESSION_ZONES ) {
					TemporalPreservationOffsetTests.inSession( factory, null, zone, session -> {
						final int id = ++ids[0];
						final var deleted = new SoftDeleted();
						deleted.id = id;
						session.persist( deleted );
						if ( temporalTables ) {
							final var withHistory = new WithHistory();
							withHistory.id = id;
							session.persist( withHistory );
						}
						session.flush();
						session.remove( deleted );
						session.flush();
						session.clear();

						// the current row is found by comparison with its row start
						if ( temporalTables ) {
							assertThat( session.find( WithHistory.class, id ) ).isNotNull();
						}
						assertThat( session.find( SoftDeleted.class, id ) ).isNull();
						for ( String query : temporalTables
								? new String[] {
										"select effective_from from WithHistory where id = " + id,
										"select deleted from SoftDeleted where id = " + id
								}
								: new String[] { "select deleted from SoftDeleted where id = " + id } ) {
							final Instant stored = session.createNativeQuery( query, Instant.class ).getSingleResult();
							assertThat( Duration.between( Instant.now(), stored ).abs() )
									.as( query + ", timestamps from database: " + fromDatabase )
									.isLessThan( Duration.ofMinutes( 5 ) );
						}
					} );
				}
			}
		}
	}

	/// Two columns which hold the same instant compare as equal. Where one
	/// holds the date and time at UTC and the other denotes an instant by
	/// itself, the database would compare them in the time zone of its
	/// session, so the comparison is rejected.
	@Test
	void columnsAreComparedByTheirInstantOrNotAtAll() {
		// only HSQLDB has columns of both kinds
		final boolean rejected = DialectContext.getDialect() instanceof HSQLDialect;
		inEverySessionZone( session -> {
			final var entity = new Compared();
			entity.id = 1;
			entity.inTwoColumns = OffsetDateTime.of( 2021, 3, 14, 11, 0, 0, 0, ZoneOffset.ofHours( 2 ) );
			entity.normalized = entity.inTwoColumns;
			entity.instant = entity.inTwoColumns.toInstant();
			session.persist( entity );
			session.flush();
			for ( String predicate : new String[] {
					"e.inTwoColumns = e.normalized",
					"e.inTwoColumns between e.normalized and e.normalized",
					"e.instant = e.normalized",
					"e.instant in (e.normalized)",
					// tuples are compared element by element
					"(e.id, e.instant) = (e.id, e.normalized)",
					"(e.id, e.instant) in ((e.id, e.normalized))",
					// as is what a subquery selects
					"e.instant = (select o.normalized from Compared o where o.id = e.id)",
					"e.instant in (select o.normalized from Compared o)",
					"e.instant = any (select o.normalized from Compared o)",
					"(e.id, e.instant) in (select o.id, o.normalized from Compared o)"
			} ) {
				final String query = "select count(e) from Compared e where " + predicate;
				if ( rejected ) {
					assertThatThrownBy( () -> session.createQuery( query, Long.class ).getSingleResult() )
							.as( predicate )
							.hasStackTraceContaining( "in the time zone of its session" );
				}
				else {
					assertThat( session.createQuery( query, Long.class ).getSingleResult() ).as( predicate ).isEqualTo( 1L );
				}
			}
			if ( rejected ) {
				// forms which not every database accepts
				for ( String predicate : new String[] {
						// a tuple within a tuple
						"(e.id, (e.id, e.instant)) = (e.id, (e.id, e.normalized))",
						// every branch of a union
						"e.instant = (select x.instant from Compared x where 1 = 0"
								+ " union all select y.normalized from Compared y)",
						"e.instant in (select x.instant from Compared x union all select y.normalized from Compared y)"
				} ) {
					final String query = "select count(e) from Compared e where " + predicate;
					assertThatThrownBy( () -> session.createQuery( query, Long.class ).getSingleResult() )
							.as( predicate )
							.hasStackTraceContaining( "in the time zone of its session" );
				}
			}
			// both hold the date and time at UTC, or both denote an instant
			assertThat( session.createQuery( "select count(e) from Compared e where e.inTwoColumns = e.instant", Long.class )
					.getSingleResult() ).isEqualTo( 1L );
		} );
	}

	/// A stored instant is compared with the current instant by its
	/// instant, also where the column holds the date and time at UTC and
	/// the current timestamp of the database is in the time zone of its
	/// session. Compared with an instant, `current_timestamp` and
	/// `local datetime` stand for the current instant, also as what a date
	/// and time is computed from.
	@Test
	void storedInstantIsComparedWithTheCurrentInstant() {
		inEverySessionZone( session -> {
			persistAnHourAgoAndAnHourAhead( session );
			for ( String attribute : new String[] { "instant", "inTwoColumns", "normalized" } ) {
				// on HSQLDB a date-time in a single column has a time zone, and the others have none
				final String current = DialectContext.getDialect() instanceof HSQLDialect && attribute.equals( "normalized" )
						? "offset datetime"
						: "instant";
				for ( String predicate : new String[] {
						"e.# < " + current,
						"e.# < current_timestamp",
						"e.# < current timestamp",
						"e.# < local datetime",
						"local datetime > e.#",
						"e.# between current_timestamp - 2 hour and current_timestamp",
						"e.# between local datetime - 2 hour and local datetime + 30 minute",
						"e.# > local datetime - 1 day and e.# < current_timestamp"
				} ) {
					final String query = "select e.id from Compared e where " + predicate.replace( "#", attribute );
					assertThat( session.createQuery( query, Integer.class ).getResultList() ).as( query )
							.containsExactly( 1 );
				}
			}
			assertThat( session.createQuery(
					"select e.id from Compared e where current_timestamp between e.instant and e.instant + 2 hour",
					Integer.class
			).getResultList() ).containsExactly( 1 );
		} );
	}

	/// The current date of the database is in the time zone of its session,
	/// or of the server. Compared with an instant which the column holds as
	/// its date and time at UTC, the result would depend on that time zone,
	/// so the comparison is rejected. The same holds on SQL Server, which
	/// reads a date and time without a time zone as being at UTC.
	@Test
	void comparisonWithTheCurrentDateIsRejectedWhereItWouldBeWrong() {
		final Dialect dialect = DialectContext.getDialect();
		inEverySessionZone( session -> {
			persistAnHourAgoAndAnHourAhead( session );
			for ( String attribute : new String[] { "instant", "inTwoColumns", "normalized" } ) {
				// on HSQLDB a date-time in a single column has a time zone
				final boolean rejected = dialect instanceof MySQLDialect
						|| dialect instanceof SQLServerDialect
						|| dialect instanceof HSQLDialect && !attribute.equals( "normalized" );
				for ( String current : new String[] { "current_date", "local date", "local date + 1 day" } ) {
					final String query = "select e.id from Compared e where e." + attribute + " < " + current;
					if ( rejected ) {
						assertThatThrownBy( () -> session.createQuery( query, Integer.class ).getResultList() )
								.as( query )
								.hasStackTraceContaining( "the result would depend on that time zone" );
					}
					else {
						// the database reads the date in the time zone of its session
						session.createQuery( query, Integer.class ).getResultList();
					}
				}
			}
		} );
	}

	/// The current time of the database is in the time zone of its session.
	/// Compared with an `OffsetTime` which the column holds as its time at
	/// UTC, the result would depend on that time zone, so the comparison is
	/// rejected.
	@Test
	void comparisonOfATimeHeldAtUtcWithTheCurrentTimeIsRejected() {
		final var builder = ServiceRegistryUtil.serviceRegistryBuilder();
		builder.applySetting( "hibernate.hbm2ddl.auto", "create-drop" );
		builder.applySetting( MappingSettings.TEMPORAL_PRESERVATION, true );
		try ( var registry = builder.build();
				var factory = (SessionFactoryImplementor) new MetadataSources( registry )
						.addAnnotatedClass( TemporalPreservationOffsetTimeTests.WithNormalizedOffsetTime.class )
						.buildMetadata()
						.buildSessionFactory() ) {
			// with the NORMALIZED policy the column holds the time at UTC, and has no time zone
			assertThat( factory.getMappingMetamodel()
					.getEntityDescriptor( TemporalPreservationOffsetTimeTests.WithNormalizedOffsetTime.class )
					.findAttributeMapping( "theValue" )
					.getSingleJdbcMapping()
					.getJdbcType()
					.getDefaultSqlTypeCode() ).isNotEqualTo( SqlTypes.TIME_WITH_TIMEZONE );
			for ( String current : new String[] { "local time", "current_time", "current time" } ) {
				final String query = "select e.id from WithNormalizedOffsetTime e where e.theValue < " + current;
				factory.inTransaction( session -> assertThatThrownBy(
						() -> session.createQuery( query, Integer.class ).getResultList() )
						.as( query )
						.hasStackTraceContaining( "the result would depend on that time zone" ) );
			}
		}
	}

	private static void persistAnHourAgoAndAnHourAhead(Session session) {
		final Instant now = Instant.now().truncatedTo( ChronoUnit.SECONDS );
		for ( int id = 1; id <= 2; id++ ) {
			final var entity = new Compared();
			entity.id = id;
			entity.instant = id == 1 ? now.minus( 1, ChronoUnit.HOURS ) : now.plus( 1, ChronoUnit.HOURS );
			entity.inTwoColumns = entity.instant.atOffset( ZoneOffset.ofHours( 2 ) );
			entity.normalized = entity.inTwoColumns;
			session.persist( entity );
		}
		session.flush();
	}

	private static void inEverySessionZone(Consumer<Session> action) {
		final var builder = ServiceRegistryUtil.serviceRegistryBuilder();
		builder.applySetting( "hibernate.hbm2ddl.auto", "create-drop" );
		builder.applySetting( MappingSettings.TEMPORAL_PRESERVATION, true );
		try ( var registry = builder.build();
				var factory = (SessionFactoryImplementor) new MetadataSources( registry )
						.addAnnotatedClass( WithGenerated.class )
						.addAnnotatedClass( Compared.class )
						.buildMetadata()
						.buildSessionFactory() ) {
			for ( String zone : DATABASE_SESSION_ZONES ) {
				TemporalPreservationOffsetTests.inSession( factory, null, zone, action );
			}
		}
	}

	@Entity(name = "WithGenerated")
	static class WithGenerated {
		@Id
		Integer id;
		@CurrentTimestamp(source = SourceType.DB)
		Instant recordedAt;
		@CurrentTimestamp(source = SourceType.DB)
		@TimeZoneRepresentation(TimeZoneRepresentation.Type.INLINE)
		@TemporalPreservationPolicy(TemporalPreservationPolicy.Type.NORMALIZED)
		OffsetDateTime normalizedAt;
	}

	@Entity(name = "WithGeneratedVersion")
	static class WithGeneratedVersion {
		@Id
		Integer id;
		String name;
		@Version
		@CurrentTimestamp(source = SourceType.DB)
		Instant version;
	}

	@Entity(name = "WithGeneratedOffsetVersion")
	static class WithGeneratedOffsetVersion {
		@Id
		Integer id;
		String name;
		@Version
		@CurrentTimestamp(source = SourceType.DB)
		@TimeZoneRepresentation(TimeZoneRepresentation.Type.INLINE)
		@TemporalPreservationPolicy(TemporalPreservationPolicy.Type.NORMALIZED)
		OffsetDateTime version;
	}

	@Entity(name = "SoftDeleted")
	@SoftDelete(strategy = SoftDeleteType.TIMESTAMP)
	static class SoftDeleted {
		@Id
		Integer id;
	}

	@Temporal(rowStart = "effective_from", rowEnd = "effective_to")
	@Entity(name = "WithHistory")
	static class WithHistory {
		@Id
		Integer id;
	}

	@Entity(name = "Compared")
	static class Compared {
		@Id
		Integer id;
		@TimeZoneRepresentation(TimeZoneRepresentation.Type.COLUMN)
		OffsetDateTime inTwoColumns;
		@TimeZoneRepresentation(TimeZoneRepresentation.Type.INLINE)
		@TemporalPreservationPolicy(TemporalPreservationPolicy.Type.NORMALIZED)
		OffsetDateTime normalized;
		Instant instant;
	}
}
