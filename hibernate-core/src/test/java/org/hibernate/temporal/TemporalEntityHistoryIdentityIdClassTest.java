package org.hibernate.temporal;

import java.time.Instant;

import org.hibernate.annotations.Temporal;
import org.hibernate.cfg.StateManagementSettings;

import org.hibernate.testing.orm.junit.DialectFeatureChecks;
import org.hibernate.testing.orm.junit.DomainModel;
import org.hibernate.testing.orm.junit.JiraKey;
import org.hibernate.testing.orm.junit.RequiresDialectFeature;
import org.hibernate.testing.orm.junit.ServiceRegistry;
import org.hibernate.testing.orm.junit.SessionFactory;
import org.hibernate.testing.orm.junit.SessionFactoryScope;
import org.hibernate.testing.orm.junit.Setting;
import org.junit.jupiter.api.Test;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;

import static org.hibernate.testing.orm.junit.DialectContext.awaitTimestampTick;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;

/**
 * A temporal entity with a history table and an {@link IdClass} of which one
 * attribute is generated by {@code IDENTITY} and the other is assigned.
 */
@SessionFactory
@DomainModel(annotatedClasses = TemporalEntityHistoryIdentityIdClassTest.Animal.class)
@ServiceRegistry(settings = @Setting(name = StateManagementSettings.TEMPORAL_TABLE_STRATEGY, value = "HISTORY_TABLE"))
@RequiresDialectFeature(feature = DialectFeatureChecks.SupportsIdentityColumns.class)
@JiraKey("HHH-21060")
class TemporalEntityHistoryIdentityIdClassTest {

	@Temporal(rowStart = "effective_from", rowEnd = "effective_to")
	@Entity(name = "HistoryMixedIdAnimal")
	@IdClass(AnimalId.class)
	static class Animal {
		@Id
		@GeneratedValue(strategy = GenerationType.IDENTITY)
		Long id;
		@Id
		@Column(name = "sub_id")
		Long subId;
		String name;
	}

	static class AnimalId {
		Long id;
		Long subId;

		AnimalId() {
		}

		AnimalId(Long id, Long subId) {
			this.id = id;
			this.subId = subId;
		}
	}

	@Test
	void testPersistWithIdentityIdClass(SessionFactoryScope scope) {
		final var animal = new Animal();
		animal.subId = 7L;
		animal.name = "original";
		scope.getSessionFactory().inTransaction( session -> session.persist( animal ) );
		assertNotNull( animal.id );
		final var key = new AnimalId( animal.id, 7L );

		awaitTimestampTick();
		final var instant = Instant.now();
		awaitTimestampTick();
		scope.getSessionFactory().inTransaction(
				session -> session.find( Animal.class, key ).name = "updated"
		);

		scope.getSessionFactory().inTransaction(
				session -> assertEquals( "updated", session.find( Animal.class, key ).name )
		);
		try (var session = scope.getSessionFactory().withOptions().asOf( instant ).open()) {
			session.inTransaction(
					tx -> assertEquals( "original", session.find( Animal.class, key ).name )
			);
		}
	}
}
