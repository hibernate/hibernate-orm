package org.hibernate.temporal.audit;

import org.hibernate.SharedSessionContract;
import org.hibernate.annotations.Audited;
import org.hibernate.cfg.StateManagementSettings;
import org.hibernate.temporal.spi.ChangesetIdentifierSupplier;

import org.hibernate.testing.orm.junit.AuditedTest;
import org.hibernate.testing.orm.junit.DialectFeatureChecks;
import org.hibernate.testing.orm.junit.DomainModel;
import org.hibernate.testing.orm.junit.JiraKey;
import org.hibernate.testing.orm.junit.RequiresDialectFeature;
import org.hibernate.testing.orm.junit.ServiceRegistry;
import org.hibernate.testing.orm.junit.SessionFactory;
import org.hibernate.testing.orm.junit.SessionFactoryScope;
import org.hibernate.testing.orm.junit.Setting;
import org.junit.jupiter.api.Test;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;

/**
 * An audited entity with an {@link IdClass} of which one attribute is generated by
 * {@code IDENTITY} and the other is assigned.
 */
@AuditedTest
@SessionFactory
@DomainModel(annotatedClasses = AuditIdentityIdClassTest.Animal.class)
@ServiceRegistry(settings = @Setting(name = StateManagementSettings.CHANGESET_ID_SUPPLIER,
		value = "org.hibernate.temporal.audit.AuditIdentityIdClassTest$TxIdSupplier"))
@RequiresDialectFeature(feature = DialectFeatureChecks.SupportsIdentityColumns.class)
@JiraKey("HHH-21060")
class AuditIdentityIdClassTest {
	private static int currentTxId;

	public static class TxIdSupplier implements ChangesetIdentifierSupplier<Integer> {
		@Override
		public Integer generateIdentifier(SharedSessionContract session) {
			return ++currentTxId;
		}
	}

	@Audited
	@Entity(name = "MixedIdAnimal")
	@IdClass(AnimalId.class)
	static class Animal {
		@Id
		@GeneratedValue(strategy = GenerationType.IDENTITY)
		Long id;
		@Id
		@Column(name = "sub_id")
		Long subId;
		String name;
	}

	static class AnimalId {
		Long id;
		Long subId;

		AnimalId() {
		}

		AnimalId(Long id, Long subId) {
			this.id = id;
			this.subId = subId;
		}
	}

	@Test
	void testPersistUpdateDelete(SessionFactoryScope scope) {
		currentTxId = 0;
		final var animal = new Animal();
		animal.subId = 7L;
		animal.name = "original";
		scope.inTransaction( session -> session.persist( animal ) );
		assertNotNull( animal.id );
		final var key = new AnimalId( animal.id, 7L );
		scope.inTransaction( session -> session.find( Animal.class, key ).name = "updated" );
		scope.inTransaction( session -> session.remove( session.find( Animal.class, key ) ) );

		assertEquals( "original", findAt( scope, 1, key ).name );
		assertEquals( "updated", findAt( scope, 2, key ).name );
		assertNull( findAt( scope, 3, key ) );
	}

	private static Animal findAt(SessionFactoryScope scope, int changeset, AnimalId key) {
		try (var session = scope.getSessionFactory().withOptions().atChangeset( changeset ).openSession()) {
			return session.find( Animal.class, key );
		}
	}
}
